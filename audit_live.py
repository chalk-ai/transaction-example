"""Live counterpart to audit_resolvers.py: query every feature and report failures.

The static audit proves each feature has *a* producer; this proves the engine can
actually plan and run them. Queries one feature at a time so a single bad
feature doesn't mask the rest.

Run with: uv run python audit_live.py [branch]
"""

import sys
from pathlib import Path

from chalk.client import ChalkClient
from chalk.features import FeatureSetBase
from chalk.importer import import_all_files

from audit_resolvers import canonical, deployable_files

REPO_ROOT = Path(__file__).parent

# Root namespaces we can supply a primary key for, and a key known to exist.
ROOTS = {"user": 5, "transaction": 1, "payment": 1}


def main() -> None:
    branch = sys.argv[1] if len(sys.argv) > 1 else None
    import_all_files(file_allowlist=deployable_files(), project_root=REPO_ROOT)
    client = ChalkClient(branch=branch)

    failures: list[tuple[str, str]] = []
    checked = 0

    for namespace, pkey in ROOTS.items():
        cls = FeatureSetBase.registry[namespace]
        for f in cls.features:
            if f.is_autogenerated or f.primary or f.is_has_many or f.is_has_one:
                continue
            name = canonical(f)
            checked += 1
            result = client.query(
                input={f"{namespace}.id": pkey},
                output=[name],
            )
            if result.errors:
                failures.append((name, result.errors[0].message))

    print(f"checked {checked} features against branch={branch or 'default'}\n")
    if not failures:
        print("Every feature planned and resolved.")
        return
    print(f"{len(failures)} feature(s) failed:\n")
    for name, message in failures:
        print(f"  {name}\n    {message.splitlines()[0]}")


if __name__ == "__main__":
    main()
