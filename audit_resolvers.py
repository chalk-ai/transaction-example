"""Audit: report every scalar feature that nothing can produce.

Planning fails at query time with

    Failed to find any valid resolver for feature: '<name>' and no `default`
    value or `max_staleness` was specified

whenever a requested feature has no producer. This script finds those features
statically, so the gap shows up before a query does.

A feature counts as producible when it is a primary key or feature time, has an
expression, is windowed, has a default or is optional, is cached
(`max_staleness > 0`), is a join key used by some relationship, or is the output
of some resolver.

Run with: uv run python audit_resolvers.py
"""

from datetime import timedelta
from pathlib import Path

from chalk.features import Feature, FeatureSetBase
from chalk.features.resolver import RESOLVER_REGISTRY
from chalk.importer import get_default_combined_ignore_config, import_all_files

REPO_ROOT = Path(__file__).parent

# Sentinel chalk uses for "no default was supplied".
NO_DEFAULT = ...


def deployable_files() -> list[str]:
    """The files `chalk apply` would actually load.

    `import_all_files(check_ignores=True)` only applies the ignore config to
    Python files — `get_sql_file_resolvers` walks the tree for `.chalk.sql`
    with no ignore config at all, so ignored SQL resolvers get parsed anyway
    and report spurious failures. The CLI sidesteps this by computing the
    allowlist itself (see `chalk.cli.get_list_results`); do the same here.
    """
    ignore = get_default_combined_ignore_config(REPO_ROOT)
    return [
        str(p)
        for suffix in ("*.py", "*.chalk.sql")
        for p in REPO_ROOT.rglob(suffix)
        if not ignore.ignored(p)
    ]


def canonical(f: Feature) -> str:
    """`user.credit_report.raw` and `credit_report.raw` are the same feature.

    Resolvers may declare outputs through a relationship path, so key
    everything by the owning namespace instead of the declared path.
    """
    return f"{f.namespace}.{f.name}"


def resolver_outputs() -> set[str]:
    """Features some resolver can produce, keyed canonically."""
    produced: set[str] = set()
    for resolver in RESOLVER_REGISTRY.get_all_resolvers():
        for output in resolver.flattened_output or []:
            if output.is_has_many or output.is_has_one:
                # A relationship output carries the joined rows with it. The
                # per-column projection isn't recoverable here, so credit the
                # whole joined namespace rather than report false gaps.
                joined = output.joined_class
                if joined is not None:
                    for sub in joined.features:
                        produced.add(canonical(sub))
                continue
            produced.add(canonical(output))
    return produced


def join_keys() -> set[str]:
    """Scalars a relationship supplies via its join condition.

    `foreign_join_keys` only reports the far side, but both operands are
    supplied by the join — e.g. `User.credit_report_id == CreditReport.id`
    resolves `user.credit_report_id` off the has-one's primary key.
    """
    keys: set[str] = set()
    for _namespace, cls in FeatureSetBase.registry.items():
        for f in cls.features:
            if not (f.is_has_many or f.is_has_one) or f.join is None:
                continue
            for side in (f.join.lhs, f.join.rhs):
                if isinstance(side, Feature):
                    keys.add(canonical(side))
    return keys


def is_producible(f: Feature, produced: set[str], fks: set[str]) -> bool:
    if f.is_autogenerated or f.is_has_many or f.is_has_one:
        return True
    if f.primary or f.is_feature_time:
        return True
    if f.underscore_expression is not None:
        return True
    if f.is_windowed or f.window_duration is not None:
        return True
    if f.join is not None:
        return True
    if f.default is not NO_DEFAULT or f.typ.is_nullable:
        return True
    # max_staleness defaults to timedelta(0) ("never cache"), which does NOT
    # let a feature be served from the online store.
    if f.max_staleness is not None and f.max_staleness > timedelta(0):
        return True
    key = canonical(f)
    return key in produced or key in fks


def main() -> None:
    for failure in import_all_files(
        file_allowlist=deployable_files(), project_root=REPO_ROOT
    ):
        print(f"[import failed] {failure.filename}:\n{failure.traceback}\n")

    produced = resolver_outputs()
    fks = join_keys()
    print(f"loaded {len(list(RESOLVER_REGISTRY.get_all_resolvers()))} resolvers\n")

    missing = [
        f
        for _namespace, cls in sorted(FeatureSetBase.registry.items())
        for f in cls.features
        if not is_producible(f, produced, fks)
    ]

    if not missing:
        print("All scalar features have a producer.")
        return

    print(f"{len(missing)} feature(s) with no resolver, expression, or default:\n")
    for f in missing:
        print(f"  {canonical(f)}   ({f.typ})")


if __name__ == "__main__":
    main()
